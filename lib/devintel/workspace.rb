# frozen_string_literal: true

require "pathname"

module DevIntel
  # Owns every path DevIntel writes to inside a target repository.
  #
  #   <repository root>/.devintel/index.sqlite
  #
  # Nothing outside `.devintel/` is ever written, so DevIntel cannot disturb the
  # target application's source tree.
  class Workspace
    DIRECTORY_NAME = ".devintel"
    DATABASE_NAME  = "index.sqlite"

    attr_reader :root

    # Walks up from +start_path+ until it finds the Git repository root.
    def self.discover(start_path = Dir.pwd)
      new(Repository::Detector.new(start_path).root!)
    end

    def initialize(root)
      @root = Pathname.new(root).expand_path
    end

    def directory
      root.join(DIRECTORY_NAME)
    end

    def database_path
      directory.join(DATABASE_NAME)
    end

    # Path of +absolute_path+ relative to the repository root, for display and
    # for storage: every path in the index is repository-relative so an index is
    # reproducible regardless of where the repository is checked out.
    def relative_path(absolute_path)
      Pathname.new(absolute_path).expand_path.relative_path_from(root).to_s
    end

    # Creates `.devintel/` and keeps it out of the target repository's history.
    # The index is a derived artefact: disposable and reproducible by re-running
    # `devintel index`.
    def prepare!
      directory.mkpath
      ignore_file = directory.join(".gitignore")
      unless ignore_file.exist?
        ignore_file.write("# Generated by DevIntel. The local index is not source.\n*\n")
      end
      self
    end

    def ==(other)
      other.is_a?(Workspace) && other.root == root
    end
    alias eql? ==

    def hash
      root.hash
    end
  end
end
